_YxCet4Row _parseYxCet4Row(String wire) {
  final fields = wire.split('|');
  if (fields.length != 6 || fields.any((field) => field.trim().isEmpty)) {
    throw FormatException('Invalid YX-CET4 row: $wire');
  }
  final meanings = fields[3].split(';');
  if (meanings.length < 2 ||
      meanings.any((meaning) => meaning.trim().isEmpty)) {
    throw FormatException('YX-CET4 row needs two meanings: $wire');
  }
  return _YxCet4Row(
    fields[0],
    fields[1],
    fields[2],
    List.unmodifiable(meanings),
    fields[4],
    fields[5],
  );
}

final yxCet4DictionaryRows = List.unmodifiable(
  _yxCet4WireRows.map(_parseYxCet4Row),
